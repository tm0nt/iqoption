/** By name, for the lookups that are not a scan. */
export const CURRENCY_BY_NAME = new Map(CURRENCIES.map((currency) => [currency.name, currency]));

/**
 * The currencies this platform offers, in the order an administrator set them.
 *
 * Falls back to the ones the catalogue says money can move in, so a platform
 * that has configured nothing still offers something sensible rather than
 * nothing at all.
 */
export function offeredCurrencies(settings) {
  const wanted = settings?.["cashier.currencies"]?.offered;
  const names = Array.isArray(wanted) && wanted.length ? wanted : null;
  if (!names) return CURRENCIES.filter((currency) => currency.is_inout && currency.is_visible);
  return names.map((name) => CURRENCY_BY_NAME.get(name)).filter(Boolean);
}
