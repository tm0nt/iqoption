const COUNTRY_BY_ISO = new Map(COUNTRIES.map((c) => [c.iso, c]));
const DIAL_BY_KEY = new Map(DIAL_CODES.map((d) => [dialKey(d), d]));

/** The country select as the given locale renders it: localised names, locale order. */
export function localizedCountries(locale: AvalonLocale): AvalonCountry[] {
  const names = COUNTRY_NAMES[locale];
  return COUNTRY_ORDER[locale].flatMap((iso) => {
    const base = COUNTRY_BY_ISO.get(iso);
    return base ? [{ iso, name: names[iso] ?? base.name }] : [];
  });
}

/** The dial-code select as the given locale renders it. */
export function localizedDialCodes(locale: AvalonLocale): AvalonDialCode[] {
  const names = DIAL_NAMES[locale];
  return DIAL_ORDER[locale].flatMap((key) => {
    const base = DIAL_BY_KEY.get(key);
    return base
      ? [{ iso: base.iso, dial: base.dial, name: names[key] ?? base.name }]
      : [];
  });
}

